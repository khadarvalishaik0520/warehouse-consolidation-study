-- Run once as ACCOUNTADMIN. Two dedicated X-Small warehouses for the calibration runs, so each has its own metering.
-- CD_ROLE / CD_MONITOR: any role and resource monitor of your own; the scripts connect with connection [cdexp].
USE ROLE ACCOUNTADMIN;
CREATE WAREHOUSE IF NOT EXISTS ICDE_SZ   WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'size scaling (F2, F2b)';
CREATE WAREHOUSE IF NOT EXISTS ICDE_SUSP WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'suspend billing (F1)';
ALTER WAREHOUSE ICDE_SZ   SET RESOURCE_MONITOR = CD_MONITOR;
ALTER WAREHOUSE ICDE_SUSP SET RESOURCE_MONITOR = CD_MONITOR;
GRANT USAGE, OPERATE, MODIFY, MONITOR ON WAREHOUSE ICDE_SZ   TO ROLE CD_ROLE;
GRANT USAGE, OPERATE, MODIFY, MONITOR ON WAREHOUSE ICDE_SUSP TO ROLE CD_ROLE;
